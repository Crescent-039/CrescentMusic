import { _electron as electron } from 'playwright-core';
import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { openStore } from '../src/store.js';
import { audioHash } from '../src/library.js';

const root=path.resolve(import.meta.dirname,'..');
const profile=path.join(root,'test-results',`migration-${Date.now()}`);
const sourceFolder=path.join(profile,'old-external-library');
await fs.mkdir(sourceFolder,{recursive:true});
const source=path.join(sourceFolder,'Moonrise.mp3');
await fs.copyFile(path.join(root,'tests/fixtures/Moonrise.mp3'),source);
await fs.writeFile(path.join(sourceFolder,'Moonrise.lrc'),'[00:00]Migrated local lyrics');
const beforeHash=await audioHash(source);
const store=await openStore(path.join(profile,'crescent.sqlite'));
store.run('INSERT INTO tracks (id,path,title,artist,album,duration,format,added,favorite) VALUES (?,?,?,?,?,?,?,?,?)',['legacy-track',source,'Moonrise','Crescent Studio','First Light',3,'MP3',Date.now()-1000,1]);
store.run('INSERT INTO playlists (id,name,cover) VALUES (?,?,NULL)',['legacy-list','原来的歌单']);
store.run('INSERT INTO playlist_tracks VALUES (?,?,?)',['legacy-list','legacy-track',1]);
store.run('INSERT INTO plays (track,at) VALUES (?,?)',['legacy-track',Date.now()]);
store.run('INSERT INTO plays (track,at) VALUES (?,?)',['legacy-track',Date.now()-9*86400000]);
store.run('INSERT INTO settings VALUES (?,?)',['recent:legacy-track',JSON.stringify(Date.now())]);
store.run('INSERT INTO settings VALUES (?,?)',['playback',JSON.stringify({id:'legacy-track',position:0.2,queue:['legacy-track'],volume:0.7,mode:'list'})]);
store.db.exec('DROP INDEX tracks_content_hash; ALTER TABLE tracks DROP COLUMN content_hash; ALTER TABLE tracks DROP COLUMN cover_version; ALTER TABLE playlists DROP COLUMN cover_version');
store.db.close();
const legacyBackup=path.join(profile,'legacy-backup.sqlite');
await fs.copyFile(path.join(profile,'crescent.sqlite'),legacyBackup);
const options={cwd:root,timeout:45000,args:[`--user-data-dir=${profile}`]};
if(process.env.CRESCENT_EXE)options.executablePath=process.env.CRESCENT_EXE;else options.args.unshift(root);
const app=await electron.launch(options);
try{
  const page=await app.firstWindow();
  await page.waitForSelector('.track-row');
  await page.waitForFunction(()=>document.querySelector('#queue-count').textContent==='1');
  let snapshot=await page.evaluate(()=>window.crescent.call('snapshot'));
  const t=snapshot.tracks[0];
  assert.equal(t.id,'legacy-track');assert.equal(t.favorite,1);assert.equal(t.plays,2);assert.equal(t.weekPlays,1);
  assert.equal(t.title,'Moonrise');assert.equal(snapshot.memberships[0].track,'legacy-track');assert.equal(snapshot.playlists[0].name,'原来的歌单');
  await page.waitForFunction(async()=>Array.isArray((await window.crescent.call('snapshot')).settings.queue));
  assert.equal(path.dirname(t.path),snapshot.musicFolder);
  assert.equal(t.content_hash,beforeHash);assert.equal(await audioHash(t.path),beforeHash);assert.equal(await audioHash(source),beforeHash);
  assert.equal(await page.evaluate(()=>window.crescent.call('lyrics','legacy-track')),'[00:00]Migrated local lyrics');
  await app.evaluate(({dialog},folder)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[folder]});},sourceFolder);
  await page.evaluate(()=>window.crescent.call('import','folder'));
  snapshot=await page.evaluate(()=>window.crescent.call('snapshot'));
  assert.equal(snapshot.tracks.length,1);assert.equal(snapshot.tracks[0].plays,2);assert.equal(snapshot.tracks[0].favorite,1);
  await app.evaluate(({dialog},file)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[file]});dialog.showMessageBox=async()=>({response:1});},legacyBackup);
  assert.equal(await page.evaluate(()=>window.crescent.call('restore')),true);
  const restored=await page.evaluate(()=>window.crescent.call('snapshot'));
  assert.equal(restored.tracks[0].id,'legacy-track');assert.equal(restored.tracks[0].favorite,1);assert.equal(restored.tracks[0].plays,2);
  console.log('PASS: original schema migration, managed audio copy, source preservation, IDs, favorites, playlists, play history, sidecar lyrics and reimport deduplication');
}finally{await app.close();}
