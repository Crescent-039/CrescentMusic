import {_electron as electron} from 'playwright-core';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {openStore} from '../src/store.js';
import {audioHash} from '../src/library.js';
const root=path.resolve(import.meta.dirname,'..'),profile=path.join(root,'test-results',`taskbar-${Date.now()}`);
const music=path.join(profile,'Music');await fs.mkdir(music,{recursive:true});
const samples=44100*4,wav=Buffer.alloc(44+samples*2);
wav.write('RIFF');wav.writeUInt32LE(wav.length-8,4);wav.write('WAVEfmt ',8);wav.writeUInt32LE(16,16);wav.writeUInt16LE(1,20);wav.writeUInt16LE(1,22);wav.writeUInt32LE(44100,24);wav.writeUInt32LE(88200,28);wav.writeUInt16LE(2,32);wav.writeUInt16LE(16,34);wav.write('data',36);wav.writeUInt32LE(samples*2,40);
const source=path.join(profile,'Abyssal Circuit 两倍时长无缝衔接版.wav');await fs.writeFile(source,wav);
const managed=path.join(music,'opaque-id.wav');await fs.writeFile(managed,wav);
const store=await openStore(path.join(profile,'crescent.sqlite'));
store.run('INSERT INTO tracks(id,path,title,artist,album,duration,format,added,content_hash,favorite) VALUES (?,?,?,?,?,?,?,?,?,?)',['opaque-id',managed,'opaque-id','未知歌手','未知专辑',4,'WAV',1,await audioHash(managed),1]);
store.run("INSERT INTO plays(track,at) VALUES ('opaque-id',?)",[Date.now()-9*86400000]);store.db.close();
const options={cwd:root,args:[`--user-data-dir=${profile}`],timeout:45000};
if(process.env.CRESCENT_EXE)options.executablePath=process.env.CRESCENT_EXE;else options.args.unshift(root);
const app=await electron.launch(options);
try{
 const page=await app.firstWindow(),errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.waitForSelector('[data-track]');
 await app.evaluate(({BrowserWindow,dialog},files)=>{
  const win=BrowserWindow.getAllWindows()[0];
  const setButtons=win.setThumbarButtons.bind(win);
  win.setThumbarButtons=buttons=>{globalThis.thumbButtons=buttons;globalThis.thumbResult=setButtons(buttons);return globalThis.thumbResult;};
  dialog.showOpenDialog=async()=>({canceled:false,filePaths:files});
 },[source,path.join(root,'tests/fixtures/Moonrise.mp3')]);
 await page.locator('#import-files').click();
 await page.waitForFunction(()=>document.querySelector('#library-count').textContent==='2');
 let snapshot=await page.evaluate(()=>window.crescent.call('snapshot'));
 const repaired=snapshot.tracks.find(t=>t.id==='opaque-id');
 assert.equal(repaired.title,'Abyssal Circuit 两倍时长无缝衔接版');assert.equal(repaired.favorite,1);assert.equal(repaired.plays,1);
 await page.locator('#audio').evaluate(a=>a.muted=true);
 await page.locator('[data-track="opaque-id"] [data-action="play"]').dblclick();
 await page.waitForFunction(()=>document.querySelector('#audio').currentTime>.1);
 assert.equal(await app.evaluate(()=>globalThis.thumbResult),true);
 assert.deepEqual(await app.evaluate(()=>globalThis.thumbButtons.map(b=>b.tooltip)),['上一首','暂停','下一首','取消喜欢']);
 assert.ok((await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].getTitle())).includes('Abyssal Circuit 两倍时长无缝衔接版'));
 assert.equal(await app.evaluate(()=>globalThis.thumbButtons.every(b=>!b.icon.isEmpty())),true);
 await app.evaluate(()=>globalThis.thumbButtons[1].click());await page.waitForFunction(()=>document.querySelector('#audio').paused);
 await page.waitForFunction(()=>document.querySelector('#toggle').textContent==='▶');
 assert.equal(await app.evaluate(()=>globalThis.thumbButtons[1].tooltip),'播放');
 await app.evaluate(()=>globalThis.thumbButtons[3].click());await page.waitForFunction(()=>document.querySelector('#player-like').textContent==='♡');
 assert.equal(await app.evaluate(()=>globalThis.thumbButtons[3].tooltip),'喜欢');
 await app.evaluate(()=>globalThis.thumbButtons[2].click());await page.waitForFunction(()=>document.querySelector('#player-title').textContent==='Moonrise');
 await app.evaluate(()=>globalThis.thumbButtons[0].click());await page.waitForFunction(()=>document.querySelector('#player-title').textContent.includes('两倍时长'));
 await page.locator('#audio').evaluate(a=>a.pause());
 await page.setViewportSize({width:1100,height:760});
 await page.waitForFunction(()=>document.querySelector('#audio').paused);
 await app.evaluate(({BrowserWindow})=>{BrowserWindow.getAllWindows()[0].minimize();globalThis.thumbButtons[1].click();});
 await page.waitForFunction(()=>!document.querySelector('#audio').paused);
 await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].restore());
 await page.locator('#audio').evaluate(a=>a.pause());
 assert.deepEqual(errors,[]);
 console.log('PASS: untagged title repair, native taskbar buttons, title, playback, favorite, previous/next, resize and minimized control');
}finally{await app.close();}
